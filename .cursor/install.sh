#!/usr/bin/env bash
# Idempotent repository bootstrap for the Agri Ledger Cloud Agent environment.
# Installs a local PostgreSQL server, seeds a dev database and admin/observe
# users, writes a local-only .env, and installs npm deps.
set -euo pipefail

cd "$(dirname "$0")/.."

DB_NAME="agri"
DB_USER="agri"
DB_PASS="agri_pw_123"

echo "==> Ensuring PostgreSQL server is installed"
if ! command -v psql >/dev/null 2>&1; then
  sudo DEBIAN_FRONTEND=noninteractive apt-get update -qq
  sudo DEBIAN_FRONTEND=noninteractive apt-get install -y -qq postgresql postgresql-contrib
fi

echo "==> Starting PostgreSQL"
sudo service postgresql start || true

for _ in $(seq 1 30); do
  if sudo -u postgres pg_isready -q; then break; fi
  sleep 1
done
if ! sudo -u postgres pg_isready -q; then
  echo "!! PostgreSQL did not become ready in time" >&2
  exit 1
fi

echo "==> Creating database and application user (idempotent)"
sudo -u postgres psql -v ON_ERROR_STOP=1 <<SQL
DO \$\$
BEGIN
  IF NOT EXISTS (SELECT FROM pg_roles WHERE rolname = '${DB_USER}') THEN
    CREATE USER ${DB_USER} WITH PASSWORD '${DB_PASS}' LOGIN CREATEDB;
  ELSE
    ALTER USER ${DB_USER} WITH PASSWORD '${DB_PASS}';
  END IF;
END
\$\$;
SQL

if ! sudo -u postgres psql -tAc "SELECT 1 FROM pg_database WHERE datname='${DB_NAME}'" | grep -q 1; then
  sudo -u postgres psql -v ON_ERROR_STOP=1 -c "CREATE DATABASE ${DB_NAME} OWNER ${DB_USER};"
fi
sudo -u postgres psql -v ON_ERROR_STOP=1 -d "${DB_NAME}" -c "GRANT ALL ON SCHEMA public TO ${DB_USER};"
sudo -u postgres psql -v ON_ERROR_STOP=1 -d "${DB_NAME}" -c "ALTER SCHEMA public OWNER TO ${DB_USER};"

echo "==> Writing local .env (dev-only credentials; not for production)"
if [ ! -f .env ]; then
  cat > .env <<ENV
# Local Cloud Agent dev config (generated by .cursor/install.sh)
DATABASE_URL=postgres://${DB_USER}:${DB_PASS}@127.0.0.1:5432/${DB_NAME}
JWT_SECRET=local-dev-jwt-secret-please-change-0123456789abcdef
ENV
else
  # Older snapshots wrote mysql:// — rewrite so functions boot against Postgres.
  sed -i "s#^DATABASE_URL=mysql://.*#DATABASE_URL=postgres://${DB_USER}:${DB_PASS}@127.0.0.1:5432/${DB_NAME}#" .env
  if ! grep -q '^DATABASE_URL=' .env; then
    echo "DATABASE_URL=postgres://${DB_USER}:${DB_PASS}@127.0.0.1:5432/${DB_NAME}" >> .env
  fi
  if ! grep -q '^JWT_SECRET=' .env; then
    echo "JWT_SECRET=local-dev-jwt-secret-please-change-0123456789abcdef" >> .env
  fi
fi

echo "==> Installing npm dependencies"
npm install

echo "==> Seeding admin/observe users and schema"
node scripts/create-admin.mjs --username admin --password admin123
node scripts/create-admin.mjs --username observe --password observe123 --role observe

echo "==> Install complete"
