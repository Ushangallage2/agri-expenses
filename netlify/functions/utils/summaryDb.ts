import pool from "../db";

export type SummaryFrequency = "weekly" | "monthly";

async function ensureIntegerIdentity(table: string, column: string) {
  const cols = await pool.query(
    `SELECT is_identity, column_default
       FROM information_schema.columns
      WHERE table_schema = current_schema()
        AND table_name = $1
        AND column_name = $2`,
    [table, column]
  );
  const col = cols.rows[0] as
    | { is_identity: string; column_default: string | null }
    | undefined;
  if (!col) return;
  if (col.is_identity === "YES") return;
  if (col.column_default && String(col.column_default).includes("nextval")) {
    return;
  }
  await pool.query(
    `ALTER TABLE "${table}" ALTER COLUMN "${column}" ADD GENERATED BY DEFAULT AS IDENTITY`
  );
  await pool.query(
    `SELECT setval(pg_get_serial_sequence($1, $2), COALESCE((SELECT MAX("${column}") FROM "${table}"), 1))`,
    [table, column]
  );
}

export async function ensureSummaryTables() {
  await pool.query(`
    CREATE TABLE IF NOT EXISTS summary_emails (
      id SERIAL PRIMARY KEY,
      email VARCHAR(255) NOT NULL UNIQUE,
      created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
    )
  `);
  await pool.query(`
    CREATE TABLE IF NOT EXISTS summary_settings (
      id INT PRIMARY KEY,
      frequency VARCHAR(16) NOT NULL DEFAULT 'weekly',
      enabled SMALLINT NOT NULL DEFAULT 1,
      last_sent_at TIMESTAMP NULL,
      last_period_key VARCHAR(32) NULL
    )
  `);
  // Imported MySQL dumps often keep id as INTEGER NOT NULL with no default.
  await ensureIntegerIdentity("summary_emails", "id");
  await pool.query(
    `CREATE UNIQUE INDEX IF NOT EXISTS summary_emails_email_key ON summary_emails (email)`
  );
  await pool.query(
    `INSERT INTO summary_settings (id, frequency, enabled) VALUES (1, 'weekly', 1)
     ON CONFLICT (id) DO NOTHING`
  );
}

export async function getSummaryConfig() {
  await ensureSummaryTables();
  const settings = await pool.query(
    `SELECT frequency, enabled, last_sent_at, last_period_key FROM summary_settings WHERE id = 1`
  );
  const emails = await pool.query(
    `SELECT id, email, created_at FROM summary_emails ORDER BY email ASC`
  );
  const row = settings.rows[0] || {
    frequency: "weekly",
    enabled: 1,
    last_sent_at: null,
    last_period_key: null,
  };
  return {
    frequency: (row.frequency === "monthly" ? "monthly" : "weekly") as SummaryFrequency,
    enabled: Boolean(Number(row.enabled)),
    lastSentAt: row.last_sent_at as string | null,
    lastPeriodKey: row.last_period_key as string | null,
    emails: emails.rows as { id: number; email: string; created_at: string }[],
  };
}

export async function saveSummaryConfig(args: {
  frequency: SummaryFrequency;
  enabled: boolean;
  emails: string[];
}) {
  await ensureSummaryTables();
  await pool.query(
    `UPDATE summary_settings SET frequency = $1, enabled = $2 WHERE id = 1`,
    [args.frequency, args.enabled ? 1 : 0]
  );

  const cleaned = [
    ...new Set(
      args.emails
        .map((e) => e.trim().toLowerCase())
        .filter((e) => /^[^\s@]+@[^\s@]+\.[^\s@]+$/.test(e))
    ),
  ];

  await pool.query(`DELETE FROM summary_emails`);
  for (const email of cleaned) {
    await pool.query(
      `INSERT INTO summary_emails (email) VALUES ($1) ON CONFLICT (email) DO NOTHING`,
      [email]
    );
  }

  return getSummaryConfig();
}

export async function markSummarySent(periodKey: string) {
  await ensureSummaryTables();
  await pool.query(
    `UPDATE summary_settings SET last_sent_at = NOW(), last_period_key = $1 WHERE id = 1`,
    [periodKey]
  );
}
